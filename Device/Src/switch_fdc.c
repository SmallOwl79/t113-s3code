uint32_t switch_fdc_set_data(switch_fdc_struct *p_sw){

	if (p_sw->b_update == port_bit_need_update){

		p_sw->b_update = port_bit_ok_state;

		if(p_sw->cntrl_mode == port_control){
			if(p_sw->ON){
				gpio_set_sun(&p_sw->ON_pin,GPIO_SET);
			}
			else{
				gpio_set_sun(&p_sw->ON_pin,GPIO_RESET);
			}
		}
//		if(p_sw->cntrl_mode == shift_reg_control){
//			shift_reg_send_data(p_sw->p_shift_reg);
//		}
	}
	return 0;
}
