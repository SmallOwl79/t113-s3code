//
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////
void switch_fdc_set_func_from_ptr(uint32_t fdc32, uint32_t tmp1, uint32_t tmp2, uint8_t *ptr){
switch_fdc_struct *p_fdc;
fdc_switch_state state;
	p_fdc = (switch_fdc_struct *)fdc32;
	state = fdc_not_control;
	if((*ptr) == 1) state = fdc_on;
	if((*ptr) == 0) state = fdc_off;

	switch_fdc_on(p_fdc, state);
	switch_fdc_set_data(p_fdc);
}
