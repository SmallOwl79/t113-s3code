void switch_fdc_on(switch_fdc_struct *p_sw, fdc_switch_state state){
uint32_t *p_32;
//uint32_t data;
	if((p_sw->state != state) || (p_sw->b_update == port_bit_need_update)){
		if(state == fdc_on){
			p_sw->ON = 1;
		}
		if(state == fdc_off){
			p_sw->ON = 0;
		}
		if(p_sw->b_inveretd_ON)	p_sw->ON = ~p_sw->ON;

		p_sw->state = state;
		p_sw->b_update = port_bit_need_update;

		if(p_sw->cntrl_mode == shift_reg_control){
			p_32 = p_sw->p_shift_reg->p_data;
			*p_32 &= ~p_sw->ON_mask;
			if(p_sw->ON) *p_32 |= p_sw->ON_mask;

			p_sw->p_shift_reg->b_update = shift_reg_need_update;//��������� ����� ������ � ����!!!!
		}
	}
}
