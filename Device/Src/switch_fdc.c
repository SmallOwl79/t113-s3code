void switch_fdc_on_update(switch_fdc_struct *p_sw, fdc_switch_state state,switch_update_immediate update){
	switch_fdc_on(p_sw, state);
	if(update == now_need_update){
		switch_fdc_set_data(p_sw);
	}
}
