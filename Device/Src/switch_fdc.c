void sw_fdc_add_to_cell_table(SettingCell_t *p_cell, uint32_t num, switch_fdc_struct *p_sw, const char *p_name){
SettingCell_t 	cell;
uint32_t 		i;
	for(i=0;i<COMPONENT_MAX_TABLE_SIZE;i++){
		if(!p_cell[i].CellNumber) break;
	}
	if( i>= COMPONENT_MAX_TABLE_SIZE) return;

	cell.CellAttr = Action_Att + RD_Att + WR_Att;
	cell.CellType = FixIntegerCellType + 1;
	cell.CellNumber = num;
	cell.VarPtr = 0;
	cell.ReadProc = (void*)(void*)switch_fdc_get_func_state;
	cell.WriteProc = (void*)(void*)switch_fdc_set_func_from_ptr;
	cell.LowLim = 0;
	cell.HighLim = 0;
	cell.DefaultValue = (uint32_t)p_sw;
	cell.DescriptStr = p_name;

	p_cell[i] = cell;
}
