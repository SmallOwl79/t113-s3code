void switch_fdc_on_ptr(void *p_void){
switch_fdc_struct *p_sw;
uint32_t data;
	data = *((uint32_t*)p_void);
	if(!data) return;
	p_sw = (switch_fdc_struct *)(data);
	switch_fdc_on(p_sw, fdc_on);
	switch_fdc_set_data(p_sw);
}
