uint8_t* switch_fdc_get_func(uint32_t fdc32, uint32_t tmp1, uint32_t tmp2){
switch_fdc_struct *p_fdc;
	p_fdc = (switch_fdc_struct *)fdc32;
	p_fdc->tmp = p_fdc->ON;
	return &p_fdc->tmp;
}
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////
uint8_t* switch_fdc_get_func_state(uint32_t fdc32, uint32_t tmp1, uint32_t tmp2){
switch_fdc_struct *p_fdc;

	p_fdc = (switch_fdc_struct *)fdc32;
	p_fdc->tmp = p_fdc->ON;

	if(p_fdc->b_inveretd_ON)	{
		p_fdc->tmp = ~p_fdc->tmp;
		p_fdc->tmp &= 1;
	}
	return &p_fdc->tmp;
}
