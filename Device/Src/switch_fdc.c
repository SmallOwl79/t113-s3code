void switch_fdc_shift_init(switch_fdc_struct *p_fdc, shift_reg_struct *p_shift, uint32_t mask ){
	switch_fdc_start_init(p_fdc);

	p_fdc->cntrl_mode = shift_reg_control;
	p_fdc->p_shift_reg = p_shift;
	p_fdc->ON_mask = mask;
}
